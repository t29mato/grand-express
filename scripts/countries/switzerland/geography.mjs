/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderSwitzerlandDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 30).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 40).toFixed(1)}L${(x + 30).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 11).toFixed(1)},${(y - 15).toFixed(1)}L${x.toFixed(1)},${(y - 40).toFixed(1)}L${(x + 11).toFixed(1)},${(y - 15).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 24).toFixed(1)},${y.toFixed(1)}c7,-16 34,-16 48,0z" fill="#a8bd6a" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of PINES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 17).toFixed(1)}" width="4" height="17" fill="#6b5330"/>`,
      `<path d="M${x.toFixed(1)},${(y - 32).toFixed(1)}l-12,19h24z" fill="#2f6b3a"/>`,
    );
  }
  for (const [lo, la] of TERRACES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#7a5a3a" stroke-width="2.5" opacity=".7"><path d="M${(x - 18).toFixed(1)},${(y - 8).toFixed(1)}h36M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 14).toFixed(1)},${(y + 8).toFixed(1)}h28"/></g>`,
    );
  }
  for (const [lo, la] of MEADOWS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#c8d88a" stroke-width="3" opacity=".7"><path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 8).toFixed(1)}h32"/></g>`,
    );
  }
  return parts.join("");
}

