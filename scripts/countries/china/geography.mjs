/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderChinaDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 30).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 40).toFixed(1)}L${(x + 30).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 11).toFixed(1)},${(y - 15).toFixed(1)}L${x.toFixed(1)},${(y - 40).toFixed(1)}L${(x + 11).toFixed(1)},${(y - 15).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(`<path d="M${(x - 24).toFixed(1)},${y.toFixed(1)}c8,-16 34,-16 46,0z" fill="#8fae63" opacity=".8"/>`);
  }
  for (const [lo, la] of DUNES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 22).toFixed(1)},${y.toFixed(1)}c10,-10 20,-10 44,0" fill="none" stroke="#c8b478" stroke-width="4" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of PADDIES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#7fa8c4" stroke-width="3" opacity=".7"><path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 7).toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 14).toFixed(1)}h32"/></g>`,
    );
  }
  return parts.join("");
}

