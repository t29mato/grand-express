/**
 * 中国の地方ごとのBGM。
 *
 * 中国の伝統音楽は五音音階(宮・商・角・徴・羽)を基本に持つ。同じ5音の
 * 並びでもどの音を主音として聞かせるかで性格が変わる仕組みだが、6地方を
 * 音として聞き分けやすくするため、ここでは地方ごとに音の高さそのものも
 * 変え、そのうえで「宮調(明るい長調寄り)」「羽調(もの寂びた短調寄り)」の
 * どちらの性格に寄せるかを地方の気質に合わせて選んでいる。
 *
 *   - `hb` 華北 — 明るい宮調(ハ調)。北京・天津。京劇に通じる、整った表情。
 *   - `db` 東北 — 明るい宮調(ト調)を6地方でいちばん速く・強く弾く。
 *     二人転(アルレンヂュアン)の賑やかさを打楽器の厚さで表す。
 *   - `hd` 華東 — 明るい宮調(ヘ調)を6地方でいちばん遅く・静かに弾く。
 *     江南絲竹(蘇州・杭州・上海一帯の室内楽)の、急がない上品さ。
 *   - `hn` 華南 — 明るい宮調(変ホ調)に短い装飾音を挟む。広東音楽の
 *     はずむような節回しを意識した。
 *   - `xn` 西南 — もの寂びた羽調(イ調)。四川から雲南、そして高原の
 *     ラサまでを一つの調で束ねるため、特定の宗教音楽を模すのではなく、
 *     広く「高原の静けさ」として表す(済州を海と風の長調で表したのと
 *     同じ考え方)。6地方でいちばん遅く、いちばんまばら。
 *   - `xb` 西北 — もの寂びた羽調(ホ調)。西安から甘粛・新疆にかけての
 *     乾いた土地を、信天遊(シィンティエンヨウ)のような大きな跳躍を持つ
 *     旋律で表す。特定の民族の生きた音楽を再現するのではなく、
 *     隊商が行き交う土地という広い像として描く。
 *
 * 音量・和音数は韓国・日本の相場に合わせてある。
 */
