/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderPeruDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 29).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 38).toFixed(1)}L${(x + 29).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 11).toFixed(1)},${(y - 15).toFixed(1)}L${x.toFixed(1)},${(y - 38).toFixed(1)}L${(x + 11).toFixed(1)},${(y - 15).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 24).toFixed(1)},${y.toFixed(1)}c7,-15 33,-15 48,0z" fill="#7a8a5a" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of DESERT_SCRUB) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${x.toFixed(1)},${y.toFixed(1)}v-18M${x.toFixed(1)},${(y - 10).toFixed(1)}l-7,-7M${x.toFixed(1)},${(y - 13).toFixed(1)}l7,-7" stroke="#5a7a4a" stroke-width="3" fill="none"/>`,
    );
  }
  for (const [lo, la] of JUNGLE_PALMS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 16).toFixed(1)}" width="4" height="16" fill="#5a4326"/>`,
      `<path d="M${x.toFixed(1)},${(y - 16).toFixed(1)}q-14,-4 -18,4M${x.toFixed(1)},${(y - 16).toFixed(1)}q14,-4 18,4M${x.toFixed(1)},${(y - 16).toFixed(1)}q-11,-10 -8,-18M${x.toFixed(1)},${(y - 16).toFixed(1)}q11,-10 8,-18" stroke="#2f6b2a" stroke-width="3" fill="none"/>`,
    );
  }
  return parts.join("");
}

