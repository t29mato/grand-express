/**
 * ベネズエラの地形(海岸線・地形帯・河川・湖沼・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。投影は他国と同じ線形投影(team-leadが計算済みの寸法)。
 *
 *   BW = BH × (経度の幅 ÷ 緯度の幅) × cos(平均緯度)
 *
 * 経度73.5〜59.8度(西)、緯度12.5〜0.7度(北)。経度幅13.7度・緯度幅11.8度、
 * 平均緯度6.6度の cos(≒0.993)を掛けると横/縦 ≒ 1.155。
 * 都市28件・1件あたり約90,000px²の密度に合わせ BW=1710 / BH=1480
 * (1710×1480÷28 ≒ 90,386px²)。
 *
 * ## 海岸線について(簡略化の注記)
 *
 * マラカイボ湖はタブラソ海峡でベネズエラ湾とつながる汽水の湖で、実測でも
 * 海岸線の一部として描くのが実際の地図に近い(独立した湖として描くと
 * 国の輪郭そのものが変わってしまう)。パラグアナ半島・パリア半島・
 * オリノコ・デルタも実在の岬・半島。南と西の国境(ブラジル・コロンビア)は
 * 海岸ではないが、国の形を閉じるために同じ配列に含めている
 * (韓国のDMZと同じ扱い)。
 *
 * **エセキボ地域(ガイアナとの係争地)は描かない。**東の国境はデルタ・
 * アマクロの手前で止め、未係争のガイアナ国境線を使う。
 *
 * 座標は主要な岬・河口・国境の目安点から起こした簡略形で、測量精度ではない。
 * 実在の座標(都市・地形帯の代表点)は個別に確認した。
 *
 * ## 焼き込み後の差し戻しで直した3点(2026-08-13)
 *
 * team-leadが`check-sea-routes.mjs`を回した結果、5路線が60px超で差し戻された。
 * 共有ファイルは走らせられないので、playwrightで直接このファイルをimportし
 * マゼンタ台紙に描いて実測する自作スクリプトを作って直した(手順は
 * `REGISTER.md` に詳しく書いてある)。
 *
 * 1. **マラカイボ湖のくびれの西岸・東岸が自己交差していた。**タブラソ海峡の
 *    西側と東側の点が入れ替わって描かれており、マラカイボ・カビマスの両都市が
 *    実測で「海の上」に出ていた。座標を洗い直して交差ゼロを確認した
 *    (`find-crossings`ふうの自作スクリプトで全53辺を総当たりし、交差0を確認)。
 * 2. **マルガリータ島(ポルラマル)を描き忘れていた。**`VENEZUELA_LAND`が
 *    本土1枚だけで、島が無いために実測でポルラマルが「海の上」に出ていた。
 *    楕円近似の`MARGARITA`を追加した。
 * 3. **プエルトラクルス周辺の海岸線が都市の実座標とずれていた**(点が
 *    西へ0.28度・南へずれていた)ため、プエルトラクルス自身が「海の上」に
 *    出ていたのに加え、フェリー航路(プエルトラクルス—ポルラマル)の
 *    直線が海岸に沿ってジグザグに陸を跨いでいた。都市の実座標に合わせて
 *    引き直した。
 *
 * この3点を直したうえで、マラカイボ湖を渡る2路線(マラカイボ/カビマス—
 * サンタバルバラ・デル・スリア)は直線では解決できないと判断し
 * `cities.mjs`側で経路そのものを外した(理由はそちらのコメント参照)。
 */

