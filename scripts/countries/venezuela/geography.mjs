/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderVenezuelaDecor(px, py) {
  const parts = [];
  for (const [lo, la] of ANDES_PEAKS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 26).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 34).toFixed(1)}L${(x + 26).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 9).toFixed(1)},${(y - 13).toFixed(1)}L${x.toFixed(1)},${(y - 34).toFixed(1)}L${(x + 9).toFixed(1)},${(y - 13).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  // テプイ(頂が平らな卓状山)。エンジェル・フォールとロライマの目印。
  for (const [lo, la] of TEPUIS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 22).toFixed(1)},${y.toFixed(1)}L${(x - 15).toFixed(1)},${(y - 26).toFixed(1)}L${(x + 15).toFixed(1)},${(y - 26).toFixed(1)}L${(x + 22).toFixed(1)},${y.toFixed(1)}z" fill="#8a6a4c" opacity=".9"/>`,
      `<rect x="${(x - 15).toFixed(1)}" y="${(y - 28).toFixed(1)}" width="30" height="4" fill="#5f4a36"/>`,
    );
  }
  for (const [lo, la] of COAST_RANGE_HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 22).toFixed(1)},${y.toFixed(1)}c7,-14 30,-14 44,0z" fill="#5f7f4a" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of PALMS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 1.6).toFixed(1)}" y="${(y - 16).toFixed(1)}" width="3.2" height="16" fill="#6b5330"/>`,
      `<path d="M${x.toFixed(1)},${(y - 16).toFixed(1)}c-9,-2 -13,-8 -14,-13c6,2 11,7 14,13c3,-6 8,-11 14,-13c-1,5 -5,11 -14,13z" fill="#2f6b3a"/>`,
    );
  }
  for (const [lo, la] of LLANOS_GRASS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#8a9a4a" stroke-width="2" opacity=".7"><path d="M${(x - 10).toFixed(1)},${y.toFixed(1)}l-2,-9M${x.toFixed(1)},${y.toFixed(1)}l0,-11M${(x + 10).toFixed(1)},${y.toFixed(1)}l2,-9"/></g>`,
    );
  }
  return parts.join("");
}

