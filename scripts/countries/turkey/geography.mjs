/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderTurkeyDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 29).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 38).toFixed(1)}L${(x + 29).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 11).toFixed(1)},${(y - 15).toFixed(1)}L${x.toFixed(1)},${(y - 38).toFixed(1)}L${(x + 11).toFixed(1)},${(y - 15).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 24).toFixed(1)},${y.toFixed(1)}c8,-16 34,-16 46,0z" fill="#b3ab6a" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of OLIVES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 1.5).toFixed(1)}" y="${(y - 10).toFixed(1)}" width="3" height="10" fill="#6b6330"/>`,
      `<circle cx="${x.toFixed(1)}" cy="${(y - 14).toFixed(1)}" r="8" fill="#8a9a5c"/>`,
    );
  }
  for (const [lo, la] of WHEATFIELDS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#d4b84a" stroke-width="3" opacity=".75"><path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 7).toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 14).toFixed(1)}h32"/></g>`,
    );
  }
  for (const [lo, la] of VINES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#5f7f4a" stroke-width="2" opacity=".8"><path d="M${(x - 14).toFixed(1)},${y.toFixed(1)}h28M${(x - 14).toFixed(1)},${(y + 6).toFixed(1)}h28"/></g>`,
    );
  }
  return parts.join("");
}

