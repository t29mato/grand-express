/**
 * トルコの地形(海岸線・地形帯・河川・湖沼・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。投影は他国と同じ線形投影。
 * 緯度1度と経度1度の見た目の距離が揃うよう、盤面の幅は
 *
 *   BW = BH × (経度の幅 ÷ 緯度の幅) × cos(平均緯度)
 *
 * で決める(フランスの geography.mjs が書き残した式。**度数の幅を掛け忘れて
 * `BH × cos` だけにすると国の形が縦に伸びる**)。
 *
 * 経度25.7〜44.8度(幅19.1度)、緯度42.1〜35.8度(幅6.3度)。平均緯度38.95度の
 * cos(≒0.778)を掛けると横/縦 ≒ (19.1/6.3)×0.778 ≒ 2.358。トルコは東西に
 * 長い国なので、これで正しく横長になる(縦長に見えたら式を疑うこと)。
 * 都市43件・1件あたり約90,000px²(韓国・フランス・日本・インドと同じ密度)に
 * 合わせて BW×BH ≒ 3,870,000 とすると、BH≒1280 / BW≒3020。
 *
 * ## トラキアとアナトリアは地続きではない
 *
 * イスタンブールを挟むボスポラス海峡・マルマラ海・ダーダネルス海峡が
 * ヨーロッパ側(トラキア)とアジア側(アナトリア)を隔てている。韓国の
 * 本土+済州島+鬱陵島と同じ考え方で、**2つの陸地ポリゴンに分ける**
 * (`ANATOLIA` と `THRACE`)。イスタンブールの都市点はヨーロッパ側
 * (旧市街・スルタンアフメット地区)に置く。
 *
 * ## `seg`(1マスあたりの目安距離)
 *
 * 韓国と同じ84のままだと、トルコは横3020と広いぶん路線1本が9マス
 * (上限)近くまで伸びて数珠つなぎになる。全55路線の投影後の距離を
 * 実測すると(`node -e` で `cities.mjs` の座標を `px`/`py` に通して算出)、
 * 最長がシワス〜エルズルムの674px。**seg=140 だと最長でも4.82マス、
 * 5マスを超える路線は0本**になる(seg=120では2本が5マス超)。
 * 世界一周(150・3703×1210)に近い横長の国なので、この近辺の値になる。
 */

