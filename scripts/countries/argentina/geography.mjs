/**
 * アルゼンチンの地形(国境線・地形帯・河川・湖沼・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。投影は他国と同じ線形投影。
 *
 *   BW = BH × (経度の幅 ÷ 緯度の幅) × cos(平均緯度)
 *
 * 経度-73.6〜-53.5度(西→東)、緯度-21.8〜-55.3度(北のボリビア国境付近から
 * 南のウシュアイアまで)。経度幅19.9度・緯度幅33.5度、平均緯度-38.55度の
 * cos(≒0.782)を掛けると 横/縦 ≒ 0.594×0.782 ≒ 0.465。都市49件(当初案48件+
 * リオ・グランデ。理由は cities.mjs 末尾のコメント参照)・1件あたり約90,000px²
 * の密度に合わせ、BH=3035 / BW=1424 とした(team-lead検算済み、49件でも
 * 密度はほぼ変わらないため据え置き)。
 *
 * ## 国境線の組み立てかた
 *
 * 測量精度ではなく、主要な岬・河口・国境の屈曲点を目安点にした簡略形
 * (韓国・ペルー・ボリビア・ベネズエラと同じ扱い)。国土が南北に約4000km と
 * 極端に長いため、本土を1つのポリゴンとして大まかな輪郭のみ描き、
 * ティエラ・デル・フエゴ島(アルゼンチン領部分)だけ別ポリゴンにした。
 *
 * ## 係争地について
 *
 * **マルビナス諸島(フォークランド諸島)は描いていない。**実効支配・帰属に
 * 争いのある島であり、盤面の停まりマスの対象にもしない(韓国の独島・
 * 中国の台湾と同じ扱い)。南極半島の領有権主張も同じ理由で描かない。
 */

