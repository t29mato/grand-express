/**
 * モロッコの地形(海岸線・地形帯・河川・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。投影は他国と同じ線形投影。
 * 緯度1度と経度1度の見た目の距離が揃うよう、盤面の幅は
 *
 *   BW = BH × (経度の幅 ÷ 緯度の幅) × cos(平均緯度)
 *
 * で決める(フランス・イタリアの geography.mjs が書き残した式。**度数の幅を
 * 掛け忘れて `BH × cos` だけにすると国の形が縦に伸びる**ので注意)。
 *
 * 経度-13.2〜-1.0度(幅12.2度)、緯度36.0〜27.6度(幅8.4度)、
 * 平均緯度31.8度の cos(0.5550rad)を掛けると 横/縦 ≒ 1.2344。
 * 都市38件・1件あたり約90,000px²に合わせて BW×BH ≒ 3,420,000 とすると、
 * BH≒1665 / BW≒2055(`node -e` で実際に計算して確認済み)。
 *
 * **西サハラは含めない。**領有権が争われている地域のため(韓国の独島・
 * 中国の台湾と同じ判断)。南端はタルファヤ・タンタンの緯度(約北緯27.9度)で
 * 切ってあり、投影の南端(LAT1=27.6)ぎりぎりまで使う。
 *
 * `seg` は暫定値。cities.mjs で路線を確定させたあと、実測して直すこと
 * (docs/50-authoring/13-new-board.md の手順どおり)。
 */

