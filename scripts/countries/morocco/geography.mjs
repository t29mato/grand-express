/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderMoroccoDecor(px, py) {
  const parts = [];
  for (const [lo, la] of RIF_PEAKS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 24).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 32).toFixed(1)}L${(x + 24).toFixed(1)},${y.toFixed(1)}z" fill="#7d8f5c" opacity=".85"/>`,
    );
  }
  for (const [lo, la] of ATLAS_PEAKS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 32).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 44).toFixed(1)}L${(x + 32).toFixed(1)},${y.toFixed(1)}z" fill="#8a8f92" opacity=".9"/>`,
      `<path d="M${(x - 12).toFixed(1)},${(y - 16).toFixed(1)}L${x.toFixed(1)},${(y - 44).toFixed(1)}L${(x + 12).toFixed(1)},${(y - 16).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of DUNES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 26).toFixed(1)},${y.toFixed(1)}c9,-14 43,-14 52,0z" fill="#e0bb70" opacity=".85"/>`,
    );
  }
  for (const [lo, la] of ARGAN_TREES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 1.6).toFixed(1)}" y="${(y - 8).toFixed(1)}" width="3.2" height="8" fill="#7a5a34"/>`,
      `<circle cx="${x.toFixed(1)}" cy="${(y - 12).toFixed(1)}" r="9" fill="#7a9a4a"/>`,
    );
  }
  for (const [lo, la] of CITRUS_ROWS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#7a8f4a" stroke-width="2.4" opacity=".8"><path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 6).toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 12).toFixed(1)}h32"/></g>`,
    );
  }
  return parts.join("");
}

