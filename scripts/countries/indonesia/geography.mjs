/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderIndonesiaDecor(px, py) {
  const parts = [];
  for (const [lo, la] of VOLCANOES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 22).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 30).toFixed(1)}L${(x + 22).toFixed(1)},${y.toFixed(1)}z" fill="#6f6558" opacity=".85"/>`,
      `<path d="M${x.toFixed(1)},${(y - 30).toFixed(1)}l-3,6l3,4l3,-4z" fill="#e8443f" opacity=".8"/>`,
      `<path d="M${(x - 4).toFixed(1)},${(y - 22).toFixed(1)}q4,-6 8,0" fill="none" stroke="#c8ccc4" stroke-width="2" opacity=".6"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 20).toFixed(1)},${y.toFixed(1)}c7,-13 28,-13 40,0z" fill="#5f7f4a" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of PALMS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${x.toFixed(1)},${y.toFixed(1)}q-2,-14 -1,-20" fill="none" stroke="#6b5330" stroke-width="2.4"/>`,
      `<g fill="#3f7a3f"><path d="M${x.toFixed(1)},${(y - 20).toFixed(1)}q-10,-4 -13,2"/><path d="M${x.toFixed(1)},${(y - 20).toFixed(1)}q10,-4 13,2"/><path d="M${x.toFixed(1)},${(y - 20).toFixed(1)}q-2,-8 2,-12"/></g>`,
    );
  }
  for (const [lo, la] of RICE_TERRACES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#7fa8c4" stroke-width="2.4" opacity=".75"><path d="M${(x - 14).toFixed(1)},${y.toFixed(1)}h28M${(x - 12).toFixed(1)},${(y + 5).toFixed(1)}h24M${(x - 9).toFixed(1)},${(y + 10).toFixed(1)}h18"/></g>`,
    );
  }
  return parts.join("");
}

