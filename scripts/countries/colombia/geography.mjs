/**
 * コロンビアの地形(国境線・地形帯・河川・湖沼・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。投影は他国と同じ線形投影。
 *
 *   BW = BH × (経度の幅 ÷ 緯度の幅) × cos(平均緯度)
 *
 * 経度-79.1〜-66.9度(西→東、太平洋岸〜東部国境)、緯度12.6〜-4.3度
 * (北→南、プンタ・ガジーナス〜レティシア方面)。経度幅12.2度・緯度幅16.9度、
 * 平均緯度4.15度の cos(≒0.9974)を掛けると 横/縦 ≒ 0.722×0.9974 ≒ 0.720。
 * 都市46件・1件あたり約90,000px²の密度に合わせ、BW=1690 / BH=2350とした
 * (ペルーBH=2450とほぼ同スケール)。team-lead確認済み。
 *
 * サン・アンドレス島・プロビデンシア島(カリブ海、西経81.7度付近)はこの
 * 範囲の外にあるため、USA盤のハワイ・アラスカと同じ扱いで盤面地図には
 * 描かず、クイズの題材としてのみ扱う(team-lead承認済み)。
 *
 * ## 国境線の組み立てかた
 *
 * コロンビアはカリブ海岸・太平洋岸に加えて陸の国境が5か国ぶんある
 * (パナマ・ベネズエラ・ブラジル・ペルー・エクアドル)。測量精度ではなく、
 * 主要な岬・河口・国境の屈曲点を目安点にした簡略形(韓国・ボリビア・
 * ベネズエラ・ペルーと同じ扱い)。
 *
 * ## 係争地について
 *
 * 国境に争いのある土地は描いていない(韓国のDMZ・南アメリカのエセキボと
 * 同じ扱い)。
 */

