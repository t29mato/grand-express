/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderBrazilDecor(px, py) {
  const parts = [];
  for (const [lo, la] of RAINFOREST_CANOPY) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<circle cx="${(x - 14).toFixed(1)}" cy="${y.toFixed(1)}" r="16" fill="#2f8a4a" opacity=".8"/>`,
      `<circle cx="${(x + 12).toFixed(1)}" cy="${(y + 6).toFixed(1)}" r="14" fill="#256b3a" opacity=".8"/>`,
      `<circle cx="${x.toFixed(1)}" cy="${(y - 10).toFixed(1)}" r="13" fill="#38a058" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of CERRADO_SCRUB) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 1.5).toFixed(1)},${y.toFixed(1)}l1.5,-16l1.5,16z" fill="#8a6f3a"/>`,
      `<circle cx="${x.toFixed(1)}" cy="${(y - 16).toFixed(1)}" r="7" fill="#c2b25a"/>`,
    );
  }
  for (const [lo, la] of ARAUCARIA_PINES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 1.6).toFixed(1)}" y="${(y - 26).toFixed(1)}" width="3.2" height="26" fill="#5a4630"/>`,
      `<ellipse cx="${x.toFixed(1)}" cy="${(y - 28).toFixed(1)}" rx="15" ry="4" fill="#2f6b3a"/>`,
      `<ellipse cx="${x.toFixed(1)}" cy="${(y - 34).toFixed(1)}" rx="10" ry="3" fill="#2f6b3a"/>`,
      `<ellipse cx="${x.toFixed(1)}" cy="${(y - 39).toFixed(1)}" rx="6" ry="2.4" fill="#2f6b3a"/>`,
    );
  }
  for (const [lo, la] of COASTAL_PALMS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${x.toFixed(1)},${y.toFixed(1)}q-2,-14 -1,-20" fill="none" stroke="#6b5330" stroke-width="2.4"/>`,
      `<g stroke="#2f8a4a" stroke-width="3" fill="none"><path d="M${(x - 1).toFixed(1)},${(y - 20).toFixed(1)}q-12,-4 -16,2M${(x - 1).toFixed(1)},${(y - 20).toFixed(1)}q-10,-10 -10,-16M${(x - 1).toFixed(1)},${(y - 20).toFixed(1)}q2,-12 -2,-18M${(x - 1).toFixed(1)},${(y - 20).toFixed(1)}q10,-6 14,0M${(x - 1).toFixed(1)},${(y - 20).toFixed(1)}q8,-12 6,-18"/></g>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 26).toFixed(1)},${y.toFixed(1)}c8,-18 44,-18 52,0z" fill="#5f7f4a" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of PANTANAL_MARSH) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#7fa8c4" stroke-width="3" opacity=".7"><path d="M${(x - 18).toFixed(1)},${y.toFixed(1)}h36M${(x - 18).toFixed(1)},${(y + 8).toFixed(1)}h36"/></g>`,
    );
  }
  return parts.join("");
}

