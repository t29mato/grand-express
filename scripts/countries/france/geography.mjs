/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderFranceDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo), y = py(la);
    parts.push(
      `<path d="M${(x - 30).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 40).toFixed(1)}L${(x + 30).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 11).toFixed(1)},${(y - 15).toFixed(1)}L${x.toFixed(1)},${(y - 40).toFixed(1)}L${(x + 11).toFixed(1)},${(y - 15).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo), y = py(la);
    parts.push(`<path d="M${(x - 24).toFixed(1)},${y.toFixed(1)}c8,-16 34,-16 46,0z" fill="#5f7f4a" opacity=".8"/>`);
  }
  for (const [lo, la] of VINES) {
    const x = px(lo), y = py(la);
    // 葡萄畑は畝の短い線で表す
    parts.push(
      `<g stroke="#6b8f4a" stroke-width="3" opacity=".8"><path d="M${(x - 18).toFixed(1)},${y.toFixed(1)}h36M${(x - 18).toFixed(1)},${(y + 8).toFixed(1)}h36M${(x - 18).toFixed(1)},${(y + 16).toFixed(1)}h36"/></g>`,
    );
  }
  for (const [lo, la] of PINES) {
    const x = px(lo), y = py(la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 18).toFixed(1)}" width="4" height="18" fill="#6b5330"/>`,
      `<path d="M${x.toFixed(1)},${(y - 34).toFixed(1)}l-13,20h26z" fill="#2f6b3a"/>`,
    );
  }
  return parts.join("");
}

