/**
 * フランスの地形(海岸線・地形帯・河川・湖沼・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。投影は他国と同じ線形投影。
 * 緯度1度と経度1度の見た目の距離が揃うよう、盤面の幅は
 *
 *   BW = BH × (経度の幅 ÷ 緯度の幅) × cos(平均緯度)
 *
 * で決める。**度数の幅を掛けるのを忘れて `BH × cos` としてはいけない。**
 * 最初それで BW=1690 としてしまい、国の形が縦に1.5倍伸びていた。
 * フランスは実寸で1136km×1099km、つまりほぼ正方形(横/縦=1.03)なので、
 * 縦長に見えたらこの式を疑うこと。
 *
 * 大きさ(BW×BH)は都市1つあたりの面積で決めている。ここは50都市で
 * 約90k px²/都市。インド(90k)・日本(86k)と揃えてあり、
 * これより小さいとマーカーが団子になる。
 */

