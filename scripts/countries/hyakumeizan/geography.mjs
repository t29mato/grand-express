/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderHyakumeizanDecor(px, py) {
  const parts = [];
  for (const [lo, la] of DISTANT_PEAKS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 24).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 32).toFixed(1)}L${(x + 24).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 9).toFixed(1)},${(y - 12).toFixed(1)}L${x.toFixed(1)},${(y - 32).toFixed(1)}L${(x + 9).toFixed(1)},${(y - 12).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of PINES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 15).toFixed(1)}" width="4" height="15" fill="#6b5330"/>`,
      `<path d="M${x.toFixed(1)},${(y - 28).toFixed(1)}l-11,17h22z" fill="#2f6b3a"/>`,
    );
  }
  for (const [lo, la] of PADDIES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#7fa8c4" stroke-width="3" opacity=".75"><path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 7).toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 14).toFixed(1)}h32"/></g>`,
    );
  }
  return parts.join("");
}

