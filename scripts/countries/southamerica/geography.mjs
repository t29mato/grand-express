/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderSouthAmericaDecor(px, py) {
  const parts = [];
  for (const [lo, la] of ANDES_PEAKS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 22).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 30).toFixed(1)}L${(x + 22).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 8).toFixed(1)},${(y - 12).toFixed(1)}L${x.toFixed(1)},${(y - 30).toFixed(1)}L${(x + 8).toFixed(1)},${(y - 12).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of TEPUI_LIKE_HIGHLANDS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 18).toFixed(1)},${y.toFixed(1)}L${(x - 12).toFixed(1)},${(y - 22).toFixed(1)}L${(x + 12).toFixed(1)},${(y - 22).toFixed(1)}L${(x + 18).toFixed(1)},${y.toFixed(1)}z" fill="#8a6a4c" opacity=".9"/>`,
    );
  }
  for (const [lo, la] of AMAZON_TREES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="9" fill="#3f8f4f" opacity=".85"/>`,
      `<circle cx="${(x + 12).toFixed(1)}" cy="${(y + 4).toFixed(1)}" r="7" fill="#2f6b3a" opacity=".85"/>`,
    );
  }
  for (const [lo, la] of PAMPAS_GRASS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#8a9a4a" stroke-width="2" opacity=".7"><path d="M${(x - 9).toFixed(1)},${y.toFixed(1)}l-2,-8M${x.toFixed(1)},${y.toFixed(1)}l0,-10M${(x + 9).toFixed(1)},${y.toFixed(1)}l2,-8"/></g>`,
    );
  }
  for (const [lo, la] of PATAGONIA_SCRUB) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="5" fill="#7a8a6a" opacity=".75"/>`,
    );
  }
  for (const [lo, la] of ATACAMA_DUNES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}q8,-10 16,0q8,-10 16,0" fill="none" stroke="#a8865a" stroke-width="2" opacity=".7"/>`,
    );
  }
  return parts.join("");
}

