/**
 * 南アメリカ大陸の地形(海岸線・地形帯・河川・湖沼・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。投影は他の盤面と同じ線形投影。
 *
 *   BW = BH × (経度の幅 ÷ 緯度の幅) × cos(平均緯度)
 *
 * team-lead 計算済みの寸法(変更しない): 経度-82.0〜-34.0度(西→東)、
 * 緯度13.0〜-56.0度(北→南、カリブ海岸からフエゴ島の南まで)。
 * 経度幅48度・緯度幅69度、平均緯度-21.5度の cos(≒0.930)を掛けると
 * 横/縦 ≒ 0.6957×0.930 ≒ 0.647、BH=2500からBW≒1618(指定の1620と一致)。
 * 都市45件・1件あたり約90,000px²の密度(BW1620×BH2500÷45≒90,000)。
 *
 * px/度 は 経度 1620/48≒33.75px・緯度 2500/69≒36.23px。
 * フランス・韓国(300px/度台)に比べ大陸1枚ぶんなので**1度あたりの解像度は
 * 一桁小さい**。海岸線は主要な岬・河口・都市の実座標を目安点にした簡略形で、
 * 測量精度ではない(韓国・ベネズエラと同じ扱い)。
 *
 * ## 海岸線の組み立てかた
 *
 * - `scripts/countries/world/geography.mjs` の `SOUTH_AMERICA`(世界一周盤面の
 *   大陸縮尺の輪郭)を骨格にして、大陸専用盤面の解像度(世界一周の3倍近い
 *   BH)に合わせて中間点を足した。骨格が一致しているので、少なくとも
 *   世界一周盤面が踏んだ大きな破綻(自己交差など)は引き継いでいないはず。
 * - カリブ海岸(グアヒラ半島・マラカイボ湾・パラグアナ半島・パリア半島)は
 *   `venezuela/geography.mjs` の実測済み座標をもとに簡略化した。
 * - 北東ブラジルの海岸(サンルイス〜サルバドール)は `brazil/cities.mjs` の
 *   都市の実座標をそのまま目安点に使った。
 * - **世界一周盤面はマゼラン海峡が投影上ほぼ潰れるため、フエゴ島を本土と
 *   地続きに描いていた。**この盤面は南北方向の解像度が世界一周よりずっと
 *   高い(海峡の東西幅は緯度差にして1度未満だが、経度差で見ても数度ある)ため、
 *   ウスアイアを置く関係もあり、**フエゴ島は独立した島として分けて描いた。**
 * - **ガイアナとの係争地(エセキボ)は描かない。**オリノコ・デルタの東で
 *   止め、係争のない大まかな国境の目安で閉じる(韓国のDMZ・ベネズエラの
 *   国境と同じ扱い)。フォークランド/マルビナスは大陸の輪郭に含まれない
 *   離島なので、そもそも描いていない。
 * - **パナマのダリエン地峡は、コロンビア国境からヤビサ周辺までだけを描き、
 *   その先(パナマ運河・コスタリカ方面)は描かない。**海岸線ではなく
 *   地峡の内陸を横切る目安の閉じ線で切っている(韓国のDMZと同じ技法)。
 *   ちょうどこの閉じ線のあたりが、パンアメリカン・ハイウェイが実際に
 *   途切れる「ダリエン・ギャップ」にあたる。
 *
 * **未検証:** この盤面はまだ焼いていないので、`check-sea-routes.mjs` は
 * 走らせていない。自己交差や、都市が海に浮く/沈む問題は未確認。
 * team-lead が焼いたあとの実測で直すことを前提にしている。
 */

