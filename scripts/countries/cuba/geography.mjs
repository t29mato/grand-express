/**
 * イスラ・デ・ラ・フベントゥ。ヌエバ・ヘロナ(-82.8033, 21.8811)を
 * 中心にした楕円(オセアニア方式)。都市は常に島の中心にあるので、
 * 「頂上が都市より陸側」というノルウェー型の事故は構造的に起きない。
 *
 * **半径はここまで縮めないと航路が通らなかった。**バタバノー―ヌエバ・
 * ヘロナの航路は `use-board-layout.ts` の折れ方(L字。診断すると
 * 「対角線の脚」→「島の中心経度をそのまま通る垂直の脚」)のせいで、
 * 島へ向かう最後の脚が島の中心を真上から縦に貫く形になる。楕円が大きい
 * ほどこの脚の大半が「陸の上」と判定され、rx=0.36/ry=0.32(実測112px、
 * 60px超で不合格)ではだめだった。rx=0.15/ry=0.12まで縮めて
 * check-sea-routes.mjs が通った(2026-08-21実測、60px超0本)。
 * 都市の印(半径約10px)よりは十分大きい。
 */
function pinesIsland() {
  const cx = -82.8033;
  const cy = 21.8811;
  const rx = 0.15;
  const ry = 0.12;
  const pts = [];
  const steps = 24;
  for (let i = 0; i < steps; i++) {
    const a = (i / steps) * Math.PI * 2;
    pts.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return pts;
}

