/**
 * キューバの地形(海岸線・地形帯・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。投影は他国と同じ線形投影。
 *
 *   BW = BH × (経度の幅 ÷ 緯度の幅) × cos(平均緯度)
 *
 * 経度-85.0〜-74.0度(西のカボ・デ・サン・アントニオから東のプンタ・デ・
 * マイシまで)、緯度23.3〜19.7度(北のハバナ沖から南のカボ・クルスまで)。
 * 経度幅11.0度・緯度幅3.6度、平均緯度21.5度の cos(≒0.930)を掛けると
 * 横/縦 ≒ 3.056×0.930 ≒ 2.84。都市40件・1件あたり約90,000px²の密度に
 * 合わせ、BW=3200 / BH=1125 とした(3200×1125=3,600,000px²)。
 *
 * キューバは南北にごく薄く東西に長い島なので、盤面全体も極端な横長になる。
 * トルコ(BW3020・seg140)より横に長いため、`seg` はやや大きめの150とした
 * (実測してseg調整が要る場合は取りまとめ側に確認)。
 *
 * ## 海岸線の組み立てかた
 *
 * 実際のキューバの海岸線は湾と半島がひじょうに多い(グアカナヤボ湾、
 * バタバノー湾、ニペ湾など)。測量精度ではなく、主要な岬・湾口を目安点に
 * した簡略形(韓国・ボリビア・ベネズエラ・ペルーと同じ扱い)。
 * イスラ・デ・ラ・フベントゥは本土と離れた別の陸地として2つ目のポリゴンで
 * 描いている(1都市しかない島なので、都市の座標を中心にした楕円で描き、
 * 「都市が島の中心にあるので海に浮く事故が構造的に起きない」オセアニア方式)。
 *
 * **62頂点・105px/頂点(2026-08-21実測)。**当初38頂点・188px/頂点だった
 * ところ、team-leadの指摘で西端(ピナル・デル・リオ〜グアナアカビベス)が
 * 丸ごと落ちてビニャーレスが海に出ているのが分かった(アルゼンチン120px/
 * チリ129px/コロンビア156pxに対しキューバ188pxで最も粗かった)。
 * 西岸を中心に頂点を足して直した。都市40件はすべて陸の内側(実測済み)。
 *
 * **直す過程で1件、typoを本物の欠陥と誤認しかけた。**頂点を足すたびに
 * バタバノー―ヌエバ・ヘロナの航路が海に出たり戻ったりしたため、しばらく
 * 「頂点を足すと航路に沿って陸地判定が伸びる」という構造的な問題だと
 * 疑って対症療法を重ねたが、実際はコミット済みの値(-82.90, 22.65)を
 * 直す過程で(-82.90, 22.55)と**打ち間違えていただけ**だった。
 * `git show <直前のコミット>:このファイル` で正しい値と突き合わせて発覚。
 * **座標を1つ動かして様子を見る前に、直前の動作していた版と差分を取る。**
 */

