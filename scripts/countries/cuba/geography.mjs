/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderCubaDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 34).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 42).toFixed(1)}L${(x + 34).toFixed(1)},${y.toFixed(1)}z" fill="#7a7a68" opacity=".85"/>`,
    );
  }
  for (const [lo, la] of PALMS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 18).toFixed(1)}" width="4" height="18" fill="#6b5432"/>`,
      `<path d="M${x.toFixed(1)},${(y - 18).toFixed(1)}q-16,-5 -20,4M${x.toFixed(1)},${(y - 18).toFixed(1)}q16,-5 20,4M${x.toFixed(1)},${(y - 18).toFixed(1)}q-12,-11 -9,-20M${x.toFixed(1)},${(y - 18).toFixed(1)}q12,-11 9,-20" stroke="#2f7a35" stroke-width="3" fill="none"/>`,
    );
  }
  for (const [lo, la] of CANE_ROWS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 16).toFixed(1)},${(y - 6).toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 6).toFixed(1)}h32" stroke="#8a9a3a" stroke-width="2.5" fill="none"/>`,
    );
  }
  return parts.join("");
}

