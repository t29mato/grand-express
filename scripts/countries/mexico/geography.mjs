/**
 * メキシコの地形(海岸線・地形帯・河川・湖沼・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。投影は他国と同じ線形投影。
 * 緯度1度と経度1度の見た目の距離が揃うよう、盤面の幅は
 *
 *   BW = BH × (経度の幅 ÷ 緯度の幅) × cos(平均緯度)
 *
 * で決める(フランスの geography.mjs が書き残した式。**度数の幅を掛け忘れて
 * `BH × cos` だけにすると国の形が縦に伸びる**ので注意)。
 *
 * 西経86〜118度(経度幅32度)・北緯14〜33度(緯度幅19度)、
 * 平均緯度23.5度の cos(≒0.9171)を掛けると横/縦 ≒ (32/19) × 0.9171 ≒ 1.545
 * (横長になる)。都市45件・1件あたり約90,000px²(韓国・日本・インドと同じ密度)に
 * 合わせて BW×BH ≒ 4,050,000px² とすると、BH≒1619 / BW≒2501。
 * team-leadの検算(2026-08-19)と一致。BH=1620 / BW=2500 に丸めた。
 *
 * `seg` は140で確定(2026-08-19実測)。全51路線の投影後距離を測ると
 * 最長662px(トレオン—エルモシージョ)で、seg=140なら1〜9マスの丸めで
 * 最大5マス・**5マス超0本**になる(seg=120だと6マス超が出る)。
 * トルコと同じ値になった。
 *
 * メキシコは本土に加えて**バハカリフォルニア半島**(コルテス海=カリフォルニア湾を
 * 挟んで本土と離れた陸地)を持つため、韓国が本土・済州島・鬱陵島を別ポリゴンに
 * したのと同じく、本土とバハカリフォルニアを別のポリゴンにしてある。
 */

