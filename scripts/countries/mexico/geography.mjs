/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderMexicoDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 27).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 36).toFixed(1)}L${(x + 27).toFixed(1)},${y.toFixed(1)}z" fill="#8b7f68" opacity=".85"/>`,
      `<path d="M${(x - 9).toFixed(1)},${(y - 13).toFixed(1)}L${x.toFixed(1)},${(y - 36).toFixed(1)}L${(x + 9).toFixed(1)},${(y - 13).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 23).toFixed(1)},${y.toFixed(1)}c7,-15 32,-15 44,0z" fill="#8a5a4a" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of CACTI) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 22).toFixed(1)}" width="4" height="22" rx="2" fill="#3f7a4a"/>`,
      `<rect x="${(x - 9).toFixed(1)}" y="${(y - 15).toFixed(1)}" width="4" height="12" rx="2" fill="#3f7a4a"/>`,
      `<rect x="${(x + 5).toFixed(1)}" y="${(y - 18).toFixed(1)}" width="4" height="15" rx="2" fill="#3f7a4a"/>`,
    );
  }
  for (const [lo, la] of AGAVE_ROWS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#5f8f4a" stroke-width="3" opacity=".75"><path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 7).toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 14).toFixed(1)}h32"/></g>`,
    );
  }
  return parts.join("");
}

