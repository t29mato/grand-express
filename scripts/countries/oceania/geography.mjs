/**
 * オセアニア大陸盤面の地形(海岸線・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。**この盤面だけの事情として、経度は-180〜180に丸めず
 * 連続した数直線として扱う**(`world/geography.mjs` がアラスカを+216度と
 * 表すのと同じ手法。太平洋の実際の広がりが日付変更線をまたぐため、
 * 通常どおり±180で折り返すと太平洋が盤面の両端に分断されてしまう)。
 * サモア(西経171度)は東経188度、タヒチ(西経149度)は東経211度のように、
 * 西経の島は`360を足した値`で置いている。詳しくは `cities.mjs` の
 * ファイル冒頭コメントを参照。
 *
 * 寸法の根拠: 都市51・目安90k px²/都市 → 面積4,590,000px²。
 * 実測した都市の経度は134.24〜229.90度(幅95.66度)、緯度は-25.07〜15.21度
 * (幅40.28度)。それぞれ余裕を持たせてLON0=132・LON1=233(幅101)・
 * LAT0=17・LAT1=-27(幅44)とした。平均緯度-5度、cos(5°)≈0.9962。
 * 比 = (101/44)×0.9962 ≈ 2.286。BH = √(4,590,000/2.286) ≈ 1417 → 1420。
 * BW = 2.286×1420 ≈ 3246 → 3240。トルコ(3020×1280・比2.36)に迫る、
 * この6枚の中でも最も横長の盤面になる(太平洋の実際の広さを反映した形として、
 * team-leadに確認済み)。
 *
 * seg は56路線すべての投影後距離を実測して決めた。最長はラウトカ―ヤレン
 * (フィジー―ナウルの燐鉱輸送・郵便航路、646px)。seg=200で
 * 1マス43・2マス12・3マス1(全56本)となり、9マスに張り付く路線は無い。
 *
 * ## 島の描き方
 *
 * 都市が1つしか無い島は、Zanzibar(アフリカ盤面)と同じ手法——実寸だと
 * 数pxにしかならないので、ひとまわり大きな楕円として描く。都市が複数ある
 * 陸地(パプアニューギニア本土6都市・ニューカレドニア本島2都市)だけは、
 * 実際の海岸線に近い簡略化した多角形を手で置いた。
 */

/** 楕円を近似する多角形を作る(小さな島用)。度数、rotは度。 */
function oval(lon, lat, rlon, rlat, rot = 0, n = 12) {
  const rad = (rot * Math.PI) / 180;
  const pts = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * 2 * Math.PI;
    const x = rlon * Math.cos(a);
    const y = rlat * Math.sin(a);
    const xr = x * Math.cos(rad) - y * Math.sin(rad);
    const yr = x * Math.sin(rad) + y * Math.cos(rad);
    pts.push([+(lon + xr).toFixed(3), +(lat + yr).toFixed(3)]);
  }
  return pts;
}

