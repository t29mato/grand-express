/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderSpainDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 28).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 38).toFixed(1)}L${(x + 28).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 10).toFixed(1)},${(y - 15).toFixed(1)}L${x.toFixed(1)},${(y - 38).toFixed(1)}L${(x + 10).toFixed(1)},${(y - 15).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 24).toFixed(1)},${y.toFixed(1)}c7,-16 33,-16 45,0z" fill="#8a7a4a" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of WINDMILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 20).toFixed(1)}" width="4" height="20" fill="#e8e2d4"/>`,
      `<g stroke="#c9c2b0" stroke-width="2"><path d="M${x.toFixed(1)},${(y - 20).toFixed(1)}l14,6M${x.toFixed(1)},${(y - 20).toFixed(1)}l-14,-6M${x.toFixed(1)},${(y - 20).toFixed(1)}l14,-6M${x.toFixed(1)},${(y - 20).toFixed(1)}l-14,6"/></g>`,
    );
  }
  for (const [lo, la] of OLIVE_GROVES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g fill="#6f8a52" opacity=".8"><circle cx="${(x - 10).toFixed(1)}" cy="${y.toFixed(1)}" r="6"/><circle cx="${x.toFixed(1)}" cy="${(y - 3).toFixed(1)}" r="6"/><circle cx="${(x + 10).toFixed(1)}" cy="${y.toFixed(1)}" r="6"/></g>`,
    );
  }
  for (const [lo, la] of VINEYARDS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#7a5a3a" stroke-width="2" opacity=".75"><path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 6).toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 12).toFixed(1)}h32"/></g>`,
    );
  }
  return parts.join("");
}

