/**
 * スペインの地形。
 *
 * 座標は [経度, 緯度]。投影は他国と同じ線形投影。
 * 緯度1度と経度1度の見た目の距離が揃うよう、盤面の幅は
 *
 *   BW = BH × (経度の幅 ÷ 緯度の幅) × cos(平均緯度)
 *
 * で決める(フランスの geography.mjs が書き残した式。**度数の幅を掛け忘れて
 * `BH × cos` だけにすると国の形が縦に伸びる**ので注意)。
 *
 * 本土のみ(カナリア諸島・バレアレス諸島は含めない。理由は下記)。
 *
 * 経度 西9.5〜東3.5度(西端はガリシアのフィステーラ岬 -9.3 に余白、東端は
 * カタルーニャのクレウス岬 3.3 に余白)。緯度 北44.0〜南36.0度(北端は
 * カンタブリア海岸に余白、南端はカディス湾 36.5 に余白)。
 * 経度幅13度・緯度幅8度、平均緯度40度の cos(≒0.766)を掛けると
 * 横/縦 ≒ 1.245(横長)。
 *
 * 45都市・1都市あたり約90,000px²(フランス・日本・韓国と同じ密度)に
 * 合わせて BW×BH ≒ 4,050,000 とすると、BH≒1804 / BW≒2245。
 *
 * seg(1マスあたりの目安距離)は cities.mjs の SPAIN_EDGES(57本)の投影後
 * 直線距離を実測して決めた(取りまとめ側が焼き直す前の暫定値。折れ線の
 * 実際のマス数は edgeIndex%2 の折れ方に依存するため、この数字は目安)。
 * 最長はマドリード〜コルドバの600px。seg=84だと5マス超が6本出るが、
 * seg=110で5マス超0本になったので110を採用(フランス84よりやや広い盤面
 * なので、それに応じて大きくしている)。
 */

