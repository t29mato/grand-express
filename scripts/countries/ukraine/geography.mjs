/**
 * ウクライナの地形(海岸線・地形帯・河川・湖沼・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。投影は他国と同じ線形投影。
 *
 *   BW = BH × (経度の幅 ÷ 緯度の幅) × cos(平均緯度)
 *
 * 経度22.0〜40.3度(幅18.3)・緯度52.4〜44.3度(幅8.1)、平均緯度48.35度の
 * cos(≒0.664)を掛けると横/縦 ≒ 1.500。寸法は取りまとめ側(team-lead)が
 * 既に計算済み(BW2180×BH1450 ≒ 3,161,000px²・都市35件で1件あたり約90,300px²)
 * なので、ここでは変えていない。
 *
 * ## 占領地域の扱い(政治的な配慮ではなく、争いのある土地を遊びの
 * 止まりマスにしないという方針)
 *
 * 海岸線・国境線は**国際的に認められたウクライナの領土のまま**描く
 * (クリミア半島も陸地として輪郭に含める)。ただし `cities.mjs` では
 * クリミア半島・ドネツク州東部・ルハンシク州東部・マリウポリ・
 * メリトポリ・ヘルソン州のドニプロ川左岸(ヘルソン市より南東)には
 * 都市を置いていない。地形帯・河川もこれらの地域には
 * 「占領された/されていない」を示唆する描き分けをしていない
 * (単なる地形として描く)。
 *
 * カホフカ貯水池は2023年6月のダム決壊で大部分が干上がったが、
 * この盤面は係争地の現況に立ち入らないため、貯水池・ダムのどちらも
 * 描いていない(`KOREA_LAKES` のような盤面装飾の湖には含めない)。
 */

