/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderUkraineDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 25).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 33).toFixed(1)}L${(x + 25).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 9).toFixed(1)},${(y - 13).toFixed(1)}L${x.toFixed(1)},${(y - 33).toFixed(1)}L${(x + 9).toFixed(1)},${(y - 13).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 22).toFixed(1)},${y.toFixed(1)}c7,-14 30,-14 42,0z" fill="#5f7f4a" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of PINES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 16).toFixed(1)}" width="4" height="16" fill="#6b5330"/>`,
      `<path d="M${x.toFixed(1)},${(y - 30).toFixed(1)}l-11,18h22z" fill="#2f6b3a"/>`,
    );
  }
  for (const [lo, la] of WHEAT_FIELDS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#d8b34a" stroke-width="3" opacity=".8"><path d="M${(x - 17).toFixed(1)},${y.toFixed(1)}h34M${(x - 17).toFixed(1)},${(y + 7).toFixed(1)}h34M${(x - 17).toFixed(1)},${(y + 14).toFixed(1)}h34"/></g>`,
    );
  }
  for (const [lo, la] of SUNFLOWER_FIELDS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g>`,
      `<circle cx="${(x - 8).toFixed(1)}" cy="${y.toFixed(1)}" r="4" fill="#f4c430"/><circle cx="${(x - 8).toFixed(1)}" cy="${y.toFixed(1)}" r="1.6" fill="#5a4630"/>`,
      `<circle cx="${x.toFixed(1)}" cy="${(y + 5).toFixed(1)}" r="4" fill="#f4c430"/><circle cx="${x.toFixed(1)}" cy="${(y + 5).toFixed(1)}" r="1.6" fill="#5a4630"/>`,
      `<circle cx="${(x + 9).toFixed(1)}" cy="${y.toFixed(1)}" r="4" fill="#f4c430"/><circle cx="${(x + 9).toFixed(1)}" cy="${y.toFixed(1)}" r="1.6" fill="#5a4630"/>`,
      `</g>`,
    );
  }
  return parts.join("");
}

