/** 森(トロンデラーグ・ヘルゲランの低地)。 */
const FORESTS = [
  [11.20, 63.95],
  [11.60, 65.10],
  [10.60, 60.55],
];
/** 北極圏より北のツンドラを示す点描。 */
const TUNDRA = [
  [24.00, 70.30],
  [26.50, 70.10],
  [28.50, 69.80],
];

/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderNorwayDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 30).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 40).toFixed(1)}L${(x + 30).toFixed(1)},${y.toFixed(1)}z" fill="#7a8290" opacity=".85"/>`,
      `<path d="M${(x - 11).toFixed(1)},${(y - 16).toFixed(1)}L${x.toFixed(1)},${(y - 40).toFixed(1)}L${(x + 11).toFixed(1)},${(y - 16).toFixed(1)}z" fill="#eef4f7"/>`,
    );
  }
  for (const [lo, la] of FORESTS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 16).toFixed(1)}" width="4" height="16" fill="#5a4a30"/>`,
      `<path d="M${x.toFixed(1)},${(y - 30).toFixed(1)}l-11,18h22z" fill="#2f5a38"/>`,
    );
  }
  for (const [lo, la] of TUNDRA) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g fill="#c9d4c0" opacity=".7"><circle cx="${(x - 10).toFixed(1)}" cy="${y.toFixed(1)}" r="2.4"/><circle cx="${x.toFixed(1)}" cy="${(y + 6).toFixed(1)}" r="2.4"/><circle cx="${(x + 10).toFixed(1)}" cy="${(y - 3).toFixed(1)}" r="2.4"/></g>`,
    );
  }
  return parts.join("");
}

