/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderGermanyDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 25).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 34).toFixed(1)}L${(x + 25).toFixed(1)},${y.toFixed(1)}z" fill="#9aa0a8" opacity=".85"/>`,
      `<path d="M${(x - 9).toFixed(1)},${(y - 13).toFixed(1)}L${x.toFixed(1)},${(y - 34).toFixed(1)}L${(x + 9).toFixed(1)},${(y - 13).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 22).toFixed(1)},${y.toFixed(1)}c7,-14 30,-14 44,0z" fill="#5f7f4a" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of PINES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 16).toFixed(1)}" width="4" height="16" fill="#5a4630"/>`,
      `<path d="M${x.toFixed(1)},${(y - 30).toFixed(1)}l-11,18h22z" fill="#2f5f3f"/>`,
    );
  }
  for (const [lo, la] of VINEYARDS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#7a9a4a" stroke-width="2.4" opacity=".8"><path d="M${(x - 15).toFixed(1)},${y.toFixed(1)}h30M${(x - 15).toFixed(1)},${(y + 6).toFixed(1)}h30M${(x - 15).toFixed(1)},${(y + 12).toFixed(1)}h30"/></g>`,
    );
  }
  return parts.join("");
}

