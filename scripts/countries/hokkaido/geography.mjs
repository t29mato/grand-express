/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderHokkaidoDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 28).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 36).toFixed(1)}L${(x + 28).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 10).toFixed(1)},${(y - 14).toFixed(1)}L${x.toFixed(1)},${(y - 36).toFixed(1)}L${(x + 10).toFixed(1)},${(y - 14).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 22).toFixed(1)},${y.toFixed(1)}c7,-15 31,-15 42,0z" fill="#5f7f4a" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of PASTURES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#c8a850" stroke-width="3" opacity=".7"><path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 8).toFixed(1)}h32"/></g>`,
    );
  }
  for (const [lo, la] of FIELDS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#7fa8c4" stroke-width="3" opacity=".75"><path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 7).toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 14).toFixed(1)}h32"/></g>`,
    );
  }
  for (const [lo, la] of FORESTS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 16).toFixed(1)}" width="4" height="16" fill="#6b5330"/>`,
      `<path d="M${x.toFixed(1)},${(y - 30).toFixed(1)}l-12,18h24z" fill="#2f6b3a"/>`,
    );
  }
  return parts.join("");
}

