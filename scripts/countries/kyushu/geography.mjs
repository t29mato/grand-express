/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderKyushuDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 26).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 34).toFixed(1)}L${(x + 26).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 9).toFixed(1)},${(y - 13).toFixed(1)}L${x.toFixed(1)},${(y - 34).toFixed(1)}L${(x + 9).toFixed(1)},${(y - 13).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of VOLCANO_CONE) {
    const x = px(lo);
    const y = py(la);
    // 桜島。裾野が広い独立峰で、山頂に噴煙を添える(火口の隣で暮らす、という芯の題材)
    parts.push(
      `<path d="M${(x - 40).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 46).toFixed(1)}L${(x + 40).toFixed(1)},${y.toFixed(1)}z" fill="#6b5a52" opacity=".9"/>`,
      `<path d="M${(x - 6).toFixed(1)},${(y - 46).toFixed(1)}q4,-14 14,-22" fill="none" stroke="#9aa0a6" stroke-width="6" opacity=".7"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 22).toFixed(1)},${y.toFixed(1)}c7,-15 31,-15 42,0z" fill="#5f7f4a" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of TEA_FIELDS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#3f6b3a" stroke-width="3" opacity=".8"><path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 6).toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 12).toFixed(1)}h32"/></g>`,
    );
  }
  for (const [lo, la] of PADDIES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#7fa8c4" stroke-width="3" opacity=".75"><path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 7).toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 14).toFixed(1)}h32"/></g>`,
    );
  }
  return parts.join("");
}

