/**
 * ナバリノ島(プエルト・ウィリアムズのみが載る島)。都市が1つしかない島は
 * 手で輪郭を引かず、その都市の座標を中心にした楕円にする(オセアニア盤と
 * 同じ手法。都市は定義上、島の内側になる)。
 */
function islandEllipse(lo, la, rx, ry, n = 16) {
  const pts = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    pts.push([lo + rx * Math.cos(a), la + ry * Math.sin(a)]);
  }
  return pts;
}
