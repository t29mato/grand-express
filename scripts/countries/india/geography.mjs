/**
 * 盤面装飾のSVG断片を組み立てる。他国では legacy の `decor(el,g,PX,PY)` を
 * 評価して得ていたものを、インドでは最初から同じ形の文字列として持つ。
 * 投影関数は抽出スクリプトから渡される。
 */
export function renderIndiaDecor(px, py) {
  const parts = [];
  const at = (lo, la) => [px(lo), py(la)];

  for (const [lo, la] of MOUNTAINS) {
    const [x, y] = at(lo, la);
    parts.push(
      `<path d="M${(x - 34).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 44).toFixed(1)}L${(x + 34).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 13).toFixed(1)},${(y - 17).toFixed(1)}L${x.toFixed(1)},${(y - 44).toFixed(1)}L${(x + 13).toFixed(1)},${(y - 17).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }

  for (const [lo, la] of GHATS) {
    const [x, y] = at(lo, la);
    parts.push(
      `<path d="M${(x - 22).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 26).toFixed(1)}L${(x + 22).toFixed(1)},${y.toFixed(1)}z" fill="#3f6b3a" opacity=".8"/>`,
    );
  }

  for (const [lo, la] of PALMS) {
    const [x, y] = at(lo, la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 26).toFixed(1)}" width="4" height="26" fill="#6b5330"/>`,
      `<path d="M${x.toFixed(1)},${(y - 26).toFixed(1)}c-16,-4 -22,4 -24,10c8,-6 16,-6 24,-2c8,-4 16,-4 24,2c-2,-6 -8,-14 -24,-10z" fill="#2f7d3f"/>`,
    );
  }

  for (const [lo, la] of DUNES) {
    const [x, y] = at(lo, la);
    parts.push(
      `<path d="M${(x - 30).toFixed(1)},${y.toFixed(1)}c10,-14 26,-14 34,-4c6,-6 18,-6 26,4z" fill="#c9a45f" opacity=".8"/>`,
    );
  }

  return parts.join("");
}

