/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderAustraliaDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 30).toFixed(1)},${y.toFixed(1)}L${(x - 6).toFixed(1)},${(y - 30).toFixed(1)}L${x.toFixed(1)},${(y - 20).toFixed(1)}L${(x + 30).toFixed(1)},${y.toFixed(1)}z" fill="#9a6a42" opacity=".85"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 24).toFixed(1)},${y.toFixed(1)}c8,-16 32,-16 48,0z" fill="#6f8f4a" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of GUM_TREES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 1.6).toFixed(1)}" y="${(y - 18).toFixed(1)}" width="3.2" height="18" fill="#8a7050"/>`,
      `<ellipse cx="${(x - 7).toFixed(1)}" cy="${(y - 20).toFixed(1)}" rx="6" ry="4" fill="#7a9a5e" opacity=".9"/>`,
      `<ellipse cx="${(x + 6).toFixed(1)}" cy="${(y - 25).toFixed(1)}" rx="7" ry="4.5" fill="#7a9a5e" opacity=".9"/>`,
      `<ellipse cx="${x.toFixed(1)}" cy="${(y - 30).toFixed(1)}" rx="6" ry="4" fill="#89aa66" opacity=".9"/>`,
    );
  }
  for (const [lo, la] of RED_DIRT) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<ellipse cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" rx="20" ry="8" fill="#a8562e" opacity=".5"/>`,
    );
  }
  for (const [lo, la] of TERMITE_MOUNDS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 3).toFixed(1)},${y.toFixed(1)}Q${(x - 4).toFixed(1)},${(y - 14).toFixed(1)} ${x.toFixed(1)},${(y - 18).toFixed(1)}Q${(x + 4).toFixed(1)},${(y - 14).toFixed(1)} ${(x + 3).toFixed(1)},${y.toFixed(1)}z" fill="#7a5a3a"/>`,
    );
  }
  return parts.join("");
}

