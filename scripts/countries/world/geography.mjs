/**
 * 盤面装飾のSVG断片を組み立てる。投影関数は組み立て側から渡される。
 * 世界盤面は1度あたり約9pxなので、山は約32px幅(=3.5度)と控えめにする。
 */
export function renderWorldDecor(px, py) {
  const parts = [];

  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo), y = py(la);
    parts.push(
      `<path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 26).toFixed(1)}L${(x + 16).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 6).toFixed(1)},${(y - 16).toFixed(1)}L${x.toFixed(1)},${(y - 26).toFixed(1)}L${(x + 6).toFixed(1)},${(y - 16).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }

  for (const [lo, la] of HILLS) {
    const x = px(lo), y = py(la);
    parts.push(
      `<path d="M${(x - 14).toFixed(1)},${y.toFixed(1)}c5,-11 21,-11 28,0z" fill="#4d7a44" opacity=".8"/>`,
    );
  }

  for (const [lo, la] of CONIFERS) {
    const x = px(lo), y = py(la);
    parts.push(
      `<rect x="${(x - 1.5).toFixed(1)}" y="${(y - 8).toFixed(1)}" width="3" height="8" fill="#6b5330"/>`,
      `<path d="M${x.toFixed(1)},${(y - 24).toFixed(1)}l-8,16h16z" fill="#2f6b3a"/>`,
    );
  }

  for (const [lo, la] of PALMS) {
    const x = px(lo), y = py(la);
    parts.push(
      `<rect x="${(x - 1.5).toFixed(1)}" y="${(y - 16).toFixed(1)}" width="3" height="16" fill="#6b5330"/>`,
      `<path d="M${x.toFixed(1)},${(y - 16).toFixed(1)}c-10,-3 -14,3 -15,7c5,-4 10,-4 15,-1c5,-3 10,-3 15,1c-1,-4 -5,-10 -15,-7z" fill="#2f7d3f"/>`,
    );
  }

  for (const [lo, la] of DUNES) {
    const x = px(lo), y = py(la);
    parts.push(
      `<path d="M${(x - 18).toFixed(1)},${y.toFixed(1)}c6,-9 16,-9 21,-3c4,-4 11,-4 16,3z" fill="#c9a45f" opacity=".8"/>`,
    );
  }

  return parts.join("");
}

