/**
 * アフリカ大陸盤面の地形(海岸線・地形帯・河川・湖沼・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。投影は他国と同じ線形投影で、経度-18〜52度・
 * 緯度38〜-35.5度の矩形を盤面2268×2382に引き伸ばす。
 *
 * 寸法の根拠: 都市60・目安90k px²/都市 → 面積5,400,000px²。
 * 経度幅70・緯度幅73.5・平均緯度1.25度(赤道をまたぐため cos はほぼ1に
 * 近く、南北比にはほとんど効かない)。比 = (70/73.5)×cos(1.25°) ≈ 0.9522。
 * BH = √(5,400,000/0.9522) ≈ 2382、BW = 0.9522×2382 ≈ 2268。
 *
 * 範囲は実測の海岸線頂点(西端 -17.5=ヴェルデ岬、東端 51.4=グアルダフイ岬、
 * 北端 37.1=ボン岬、南端 -34.8=アガラス岬)より一回り広く取ってあるので、
 * どの頂点も盤面の縁で切れない。
 *
 * 海岸線の頂点は `scripts/countries/world/geography.mjs` の `AFRICA`
 * (および付随する `MADAGASCAR`・`ZANZIBAR`)を土台にしている(世界盤面で
 * 実測・調整済みの座標を再利用。アジア盤面が `EURASIA` を流用したのと同じ
 * 手法)。ただし世界盤面は大陸規模の粗い簡略化なので、**60都市すべてが
 * 陸地内に入るかを機械確認したところ、8都市が海側に出た**
 * (ダーバン・ナカラ・ワルビスベイ・ポワントノワール・コナクリ・
 * フリータウン・モンロビア・スファックス・オラン)。原因は2種類:
 * ①都市座標が海岸線の頂点とほぼ同じ値で判定がぶれるもの(ポワントノワール・
 * オラン)、②世界盤面では省略されていた半島・湾の実際の出っ張りが必要な
 * もの(コナクリ・フリータウン・モンロビアの西アフリカ諸半島、
 * ワルビスベイの潟湖、ダーバン〜リチャーズベイの湾曲、ナカラ湾)。
 * 該当区間に頂点を足すか位置をずらして直し、60都市すべてが内側に入ることを
 * point-in-polygon で再確認済み(下記「自分で確かめたこと」参照)。
 */

