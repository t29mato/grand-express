/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderBaliDecor(px, py) {
  const parts = [];
  for (const [lo, la] of VOLCANOES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 30).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 40).toFixed(1)}L${(x + 30).toFixed(1)},${y.toFixed(1)}z" fill="#5c5044" opacity=".88"/>`,
      `<path d="M${(x - 8).toFixed(1)},${(y - 30).toFixed(1)}L${x.toFixed(1)},${(y - 40).toFixed(1)}L${(x + 9).toFixed(1)},${(y - 28).toFixed(1)}z" fill="#3a3228"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 22).toFixed(1)},${y.toFixed(1)}c8,-16 34,-16 44,0z" fill="#8fae4a" opacity=".85"/>`,
    );
  }
  for (const [lo, la] of PALMS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${x.toFixed(1)},${y.toFixed(1)}c1,-10 -2,-20 0,-28" stroke="#6b5330" stroke-width="2.6" fill="none" stroke-linecap="round"/>`,
      `<g fill="#3f7f3a"><path d="M${x.toFixed(1)},${(y - 28).toFixed(1)}c-10,-4 -16,-2 -20,4c8,0 15,0 20,-1z"/><path d="M${x.toFixed(1)},${(y - 28).toFixed(1)}c10,-4 16,-2 20,4c-8,0 -15,0 -20,-1z"/><path d="M${x.toFixed(1)},${(y - 28).toFixed(1)}c-2,-8 -1,-14 2,-19c2,5 3,11 1,19z"/></g>`,
    );
  }
  for (const [lo, la] of TERRACES) {
    const x = px(lo);
    const y = py(la);
    // 棚田は等高線状に並ぶ弧で表す(段ごとに水を張った縁)
    parts.push(
      `<g stroke="#5f8f4a" stroke-width="2.4" opacity=".8" fill="none"><path d="M${(x - 20).toFixed(1)},${y.toFixed(1)}q20,-8 40,0"/><path d="M${(x - 18).toFixed(1)},${(y + 7).toFixed(1)}q18,-7 36,0"/><path d="M${(x - 16).toFixed(1)},${(y + 14).toFixed(1)}q16,-6 32,0"/></g>`,
    );
  }
  for (const [lo, la] of MERU) {
    const x = px(lo);
    const y = py(la);
    // 多層屋根の祠。下から上へ小さくなる4段の黒い笠。
    parts.push(
      `<g fill="#241a10"><path d="M${(x - 14).toFixed(1)},${y.toFixed(1)}h28l-3,-7h-22z"/><path d="M${(x - 11).toFixed(1)},${(y - 7).toFixed(1)}h22l-3,-6h-16z"/><path d="M${(x - 8).toFixed(1)},${(y - 13).toFixed(1)}h16l-2,-6h-12z"/><path d="M${(x - 5).toFixed(1)},${(y - 19).toFixed(1)}h10l-5,-8z"/></g>` +
      `<rect x="${(x - 3).toFixed(1)}" y="${y.toFixed(1)}" width="6" height="10" fill="#c9a877"/>`,
    );
  }
  return parts.join("");
}

