/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderEgyptDecor(px, py) {
  const parts = [];
  for (const [lo, la] of DUNES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 45).toFixed(1)},${y.toFixed(1)}c15,-22 60,-22 90,0c-25,14 -65,14 -90,0z" fill="#b9986a" opacity=".7"/>`,
    );
  }
  for (const [lo, la] of PALMS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 15).toFixed(1)}" width="4" height="15" fill="#6b5330"/>`,
      `<path d="M${x.toFixed(1)},${(y - 15).toFixed(1)}c-10,-6 -16,-2 -18,4c8,-2 14,0 18,2c2,-6 8,-8 18,-4c-4,4 -12,4 -18,-2z" fill="#2f7a3a"/>`,
    );
  }
  return parts.join("");
}

