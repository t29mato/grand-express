/**
 * エジプトの地形(海岸線・地形帯・河川・湖沼・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。投影は他国と同じ線形投影。
 *
 *   BW = BH × (経度の幅 ÷ 緯度の幅) × cos(平均緯度)
 *
 * 国境は実際の国土全体(西はリビア国境、南はスーダン国境、東は紅海沿岸の
 * ハラーイブ三角地帯付近まで)を取っている。**これは意図的。**この盤面の芯は
 * 「国土の95%が無人の砂漠で、人口と鉄道網がナイル本流とデルタという
 * 国土の5%足らずに押し込まれている」ことなので、シナイ半島や東方砂漠の
 * 広大な空白を切り落とさず、盤面の形そのものにその空白を語らせる。
 *
 * 経度24.5〜37.0度、緯度31.9〜21.8度。経度幅12.5度・緯度幅10.1度、
 * 平均緯度26.85度の cos(≒0.892)を掛けると横/縦 ≒ 1.104。
 * 都市41件のうち大半はナイル本流・デルタという国土の一部(経度27.2〜33.0)に
 * 集中しているため、単純な「都市数×90k px²」の密度目安はこの盤面には
 * そのまま当てはまらない(空白そのものが芯であるため)。
 * BW×BH ≒ 4,200,000 に合わせて BH≒1950 / BW≒2150 とした。
 *
 * シナイ半島は、スエズ運河の北(地峡)でアフリカ側本土と地続きになっている
 * ため、1枚の連続した陸地ポリゴンにしてある(運河は水路として描くが、
 * 陸地を分断する海としては扱わない。エル・カンタラの可動橋・フェリーが
 * 鉄道でも陸路として渡れることと整合させるため)。
 * 一方、スエズ湾はシナイと本土を隔てる本物の湾として陸地ポリゴンに
 * 湾入り込みの形で描いてある。
 */

