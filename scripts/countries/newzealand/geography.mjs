/** 盤面装飾のSVG断片。投影関数は組み立て側から渡される。 */
export function renderNewZealandDecor(px, py) {
  const parts = [];
  for (const [lo, la] of MOUNTAINS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 27).toFixed(1)},${y.toFixed(1)}L${x.toFixed(1)},${(y - 36).toFixed(1)}L${(x + 27).toFixed(1)},${y.toFixed(1)}z" fill="#8b8f98" opacity=".85"/>`,
      `<path d="M${(x - 10).toFixed(1)},${(y - 14).toFixed(1)}L${x.toFixed(1)},${(y - 36).toFixed(1)}L${(x + 10).toFixed(1)},${(y - 14).toFixed(1)}z" fill="#f2f6f8"/>`,
    );
  }
  for (const [lo, la] of HILLS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${(x - 23).toFixed(1)},${y.toFixed(1)}c7,-15 32,-15 44,0z" fill="#7a9a52" opacity=".8"/>`,
    );
  }
  for (const [lo, la] of PINES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<rect x="${(x - 2).toFixed(1)}" y="${(y - 17).toFixed(1)}" width="4" height="17" fill="#4a3f2c"/>`,
      `<path d="M${x.toFixed(1)},${(y - 32).toFixed(1)}l-12,19h24z" fill="#2f5f3f"/>`,
    );
  }
  for (const [lo, la] of PADDIES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<g stroke="#7a9a52" stroke-width="3" opacity=".7"><path d="M${(x - 16).toFixed(1)},${y.toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 7).toFixed(1)}h32M${(x - 16).toFixed(1)},${(y + 14).toFixed(1)}h32"/></g>`,
    );
  }
  return parts.join("");
}

