/**
 * ニュージーランドの地形(海岸線・地形帯・河川・湖沼・地名ラベル・盤面装飾)。
 *
 * 座標は [経度, 緯度]。投影は他国と同じ線形投影。
 * 緯度1度と経度1度の見た目の距離が揃うよう、盤面の幅は
 *
 *   BW = BH × (経度の幅 ÷ 緯度の幅) × cos(平均緯度)
 *
 * で決める(フランスの geography.mjs が書き残した式。**度数の幅を掛け忘れて
 * `BH × cos` だけにすると国の形が縦に伸びる**ので注意)。
 *
 * 経度166.0〜179.0度(フィヨルドランドから東岬まで)、緯度-34.0〜-47.5度
 * (ケープ・レインガからブラフまで)。経度幅13.0度・緯度幅13.5度、
 * 平均緯度-40.75度の cos(≒0.758)を掛けると 横/縦 ≒ 0.730。
 * 都市40件・1件あたり約90,000px²(韓国・日本・フランスと同じ密度)に
 * 合わせて BW×BH ≒ 3,600,000 とすると、BH≒2220 / BW≒1620
 * (2220×1620=3,596,400、40件で89,910px²/件)。**南北に長い盤面になる。**
 *
 * ## チャタム諸島を範囲から外した理由
 *
 * チャタム諸島(西経176.5度付近、日付変更線をまたいだ側)は、この盤面の
 * 経度範囲(東経166〜179度)に単純に足すと投影が壊れる。日付変更線の
 * 東側にある島を東経で扱うと経度差が350度近くになり、線形投影の式が
 * 破綻する(韓国の鬱陵島のような「近い離島」とは事情が違う)。
 * ニュージーランドの主要都市はどれも南北両島にあるため、盤面としての
 * 欠落は小さいと判断し、意図的に範囲から外した。
 */

