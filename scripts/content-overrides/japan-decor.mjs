/**
 * 日本の盤面装飾。legacy の `JAPAN.decor` を置き換える。
 *
 * legacy のものは**1つも描かれていなかった**。装飾は投影後のSVGとして焼き込まれるのに、
 * 上書き層が投影を変えている(西端を東経127→123.4度、盤面を1.75倍)ため、
 * 飾りだけが古い座標系に取り残され、陸のクリップで全部消えていた。
 * 投影の順序そのものは `scripts/extract-legacy-content.mjs` 側で直した。
 *
 * そのうえで legacy の中身を測ったところ、正しい投影で置き直しても
 *
 *   - 山12個 … 12個とも陸(すべて実在の山。そのまま使う)
 *   - 鳥居 9個 … **2個しか陸に乗らない**
 *   - 木 44本 … **5本しか陸に乗らない**
 *
 * だった。鳥居は `lo=136.4+i*0.9` と等間隔に東へ並べるだけの式で、
 * 太平洋へ出ていってしまう。木は地図の矩形いっぱいに撒いてクリップ任せの作り。
 * 山はそのまま、鳥居は**実在の神社**へ、木は**陸に乗ったものだけ**を採る。
 */
import { JAPAN_LAND } from "./japan-geography.mjs";
import { makeOnLand, scatterOnLand } from "./decor-scatter.mjs";

/**
 * 山。legacy の12峰をそのまま使う(富士・白山・北岳・羊蹄・越後・乗鞍・蔵王・
 * 阿蘇・桜島・石鎚・大雪・大山。いずれも実在で、12個とも陸に乗る)。
 * `[経度, 緯度, 大きさ]`。
 */
const PEAKS = [
  [138.73, 35.36, 26], // 富士山
  [137.65, 36.29, 20], // 白山
  [138.24, 35.65, 18], // 北岳(南アルプス)
  [140.9, 43.06, 16], // 羊蹄山
  [139.0, 37.6, 15], // 越後の山
  [137.1, 36.15, 17], // 乗鞍岳
  [140.3, 38.1, 14], // 蔵王
  [131.1, 32.88, 15], // 阿蘇
  [130.66, 31.59, 14], // 桜島
  [133.2, 33.77, 13], // 石鎚山
  [142.85, 43.66, 17], // 大雪山
  [133.55, 35.37, 12], // 大山
];

/**
 * 鳥居。legacy は等間隔に並べるだけで海へ出ていたので、**実在の神社**に置き直す。
 * 都市マーカーと重ならないよう、盤面上のどの町からも離れたものを選んである。
 */
const SHRINES = [
  [132.69, 35.4], // 出雲大社
  [131.37, 33.53], // 宇佐神宮
  [130.86, 31.86], // 霧島神宮
  [133.81, 34.18], // 金刀比羅宮
  [135.77, 33.84], // 熊野本宮大社
  [138.08, 36.04], // 諏訪大社
  [138.93, 35.92], // 三峯神社
  [140.63, 35.97], // 鹿島神宮
  [140.02, 38.55], // 出羽三山
];

/** 木を撒く範囲。legacy と同じ式・同じ並びで、陸に乗ったものだけを採る。 */
const TREE_COUNT = 26;

export function renderJapanDecor(px, py) {
  const parts = [];
  const onLand = makeOnLand(JAPAN_LAND, px, py, 10);

  for (const [lo, la, s] of PEAKS) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<polygon points="${x - s * 1.5},${y + s * 0.7} ${x},${y - s} ${x + s * 1.5},${y + s * 0.7}" fill="#8a7f9c"/>`,
      `<polygon points="${x - s * 0.55},${y - s * 0.3} ${x},${y - s} ${x + s * 0.55},${y - s * 0.3}` +
        ` ${x + s * 0.2},${y - s * 0.5} ${x},${y - s * 0.74} ${x - s * 0.2},${y - s * 0.5}" fill="#f6efe2"/>`,
    );
  }

  // legacy の散らしかた(等差を法でずらすだけ。乱数なし)をそのまま使い、
  // 候補を多めに作って陸に乗ったものから採る。
  const trees = scatterOnLand(
    TREE_COUNT,
    400,
    (i) => ({ lo: 128.6 + ((i * 41) % 160) / 9.0, la: 44.6 - ((i * 67) % 176) / 9.0, i }),
    onLand,
  );
  for (const { lo, la, i } of trees) {
    parts.push(
      `<circle cx="${px(lo)}" cy="${py(la)}" r="${5 + ((i * 13) % 4)}"` +
        ` fill="${i % 3 ? "#2f6b3f" : "#3f8046"}" opacity=".8"/>`,
    );
  }

  for (const [lo, la] of SHRINES) {
    const x = px(lo);
    const y = py(la);
    parts.push(
      `<path d="M${x - 7},${y + 7} v-10 M${x + 7},${y + 7} v-10 M${x - 11},${y - 4} h22 M${x - 9},${y - 8} q11,-4 18,0"` +
        ` stroke="#d4483c" stroke-width="2.6" fill="none" stroke-linecap="round"/>`,
    );
  }

  return parts.join("");
}
