/**
 * 各クイズ問題の難易度(1〜10)。
 *
 * legacy には難易度の概念が無く、盤面のマスの側に賞金だけが3段階で付いていた。
 * そのため「高額の問題」マスで誰でも知っている問題が出ることがあり、学習の階段が
 * 作れなかった(docs/40-learning-design/01-quiz-as-learning-device.md 2-5)。
 * ここで**問題そのものに難易度を付け**、出題時にプレイヤーの知識レベルに応じた
 * 難易度を選べるようにする。
 *
 * 基準は「対象国の外にいる一般的な人がどれくらい答えられそうか」。
 *   1〜3 … その国を知らなくても常識や推測で当たる
 *   4〜6 … 旅行したり少し調べたことがあれば分かる
 *   7〜8 … その国の文化・歴史に踏み込んだ知識が要る
 *   9〜10 … 現地の人や強い関心のある人でないと難しい
 *
 * 配列の添字は各国の `quiz` の並び順(=問題ID `q0`, `q1`…)に対応する。
 * **問題を並べ替えたり途中に挿入したりすると対応がずれる**ので、追加は末尾に行うこと。
 */

