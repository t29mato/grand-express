/**
 * お金の尺度。**「見せかた」と「中身」を分けて持つ。**
 *
 * ## なぜ2層に分けるか
 *
 * ゲームの釣り合いは6盤面すべて**内部の数値が同一**なことで担保されている。
 * 開始資金1200、クイズ100〜370、アイテム130〜640、出来事120〜320 ——
 * どの盤面でも同じ数字が使われていて、通貨だけが違う。
 *
 * ところが実際に画面へ出るのは `cur.mul` を掛けた値で、これが盤面ごとに
 * バラバラだった(ボリビアが1倍、他が100倍)。同じ「開始資金1200」が
 * ボリビアでは Bs 1,200(≒$174)、フランスでは €120,000(≒$130,000)と、
 * **実質で750倍ひらいていた**。
 *
 * したがって:
 *
 * - **桁の話(お土産→不動産)は `cur.mul` だけで済む。** 表示専用の倍率なので
 *   釣り合いは1ミリも動かない。内部の数値を全部掛け算し直す必要はない。
 * - **「東京タワーはバカみたいに高い」は `cost` の話。** こちらは釣り合いが動く。
 *
 * 混ぜると、値段を変えたのか見せかたを変えたのか分からなくなる。
 */

/** `_t("en|es|fr|ja")` 相当。 */
function t(source) {
  const [en, es, fr, ja] = source.split("|");
  return { en, es, fr, ja };
}

/**
 * 表示倍率。**内部の数値には触れない。**
 *
 * 狙いは2つ。
 *
 * 1. **買うのが不動産だと分かる桁にする。** 日本は12万円スタートだった。
 *    お土産を買う金額で、土地を買う金額ではない。桃鉄の1000万円スタートに
 *    合わせて100倍し、1200万円にする(数字の並びは12万→1200万で変わらない)。
 * 2. **盤面のあいだの実質を揃える。** 上の750倍のひらきを、為替で
 *    1.8倍以内に詰める。プレイヤーが通貨を換算することはないので、
 *    2倍程度のずれは見えない。750倍は見える。
 *
 * フランスと世界一周は据え置き。この2つは**もともと正しい桁だった**
 * (€120,000 は不動産の金額として通る)。下げると後退になる。
 */
