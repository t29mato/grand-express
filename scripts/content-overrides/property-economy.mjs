/**
 * `CITY_PROPS` を content に適用する。
 * 添字がずれると**別の物件を黙って書き換える**ので、件数が合わなければ落とす。
 */
export function applyCityProps(countryId, content, table) {
  for (const [cityId, entries] of Object.entries(table)) {
    const city = content.cities?.[cityId];
    if (!city) {
      throw new Error(`${countryId}: 値段を変えようとした都市 "${cityId}" がありません`);
    }
    if (entries.length !== city.props.length) {
      throw new Error(
        `${countryId}/${cityId}: 物件が ${city.props.length} 件ですが、` +
          `値段は ${entries.length} 件書かれています`,
      );
    }
    city.props = city.props.map((prop, i) => {
      const { cost, n } = entries[i];
      return { ...prop, ...(n ? { n } : {}), cost, inc: incomeFor(cost) };
    });
  }
}
