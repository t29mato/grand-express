/**
 * 物件の利回り。既存の値は 20.6〜21.3% に収まっていて、**全物件ほぼ一定**。
 * その性質は保つ(高い物件だけ利回りを下げると、4四半期しかない1年戦では
 * 目玉物件が「買うだけ損」になる)。
 *
 * 迷いは利回りではなく**流動性**から出す。手持ち3000で目玉が2800なら、
 * 買った瞬間に赤マスも次の町も受けられなくなる。そこが賭けになる。
 */
const YIELD = 0.207;

/** 既存データに合わせて偶数へ丸める。 */
function incomeFor(cost) {
  return 2 * Math.round((cost * YIELD) / 2);
}

