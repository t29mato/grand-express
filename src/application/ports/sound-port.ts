/**
 * 効果音・BGMのポート。現行コードの `Snd` エンジンに相当。
 * メソッド名・発火タイミングは legacy の呼び出し箇所(`Snd.xxx()`)にそのまま対応させている。
 */
export interface SoundPort {
  /** 通過中の地方に応じてBGMを切り替える(次の小節の頭で滑らかに切り替わる)。 */
  setRegion(regionId: string): void;
  /**
   * 終盤(残り2ヶ月)に入ったかどうか。
   *
   * **曲を差し替えるのではなく、いま鳴っている地方の曲を終盤の色に染める。**
   * 差し替えてしまうと、どの地方を走っていても最後の2ヶ月だけ同じ曲になり、
   * 「その土地を旅している」という手触りが最後で消える。
   * 速さと刻みだけを変えれば、曲は同じまま急かされる感じになる。
   */
  setFinalStretch(active: boolean): void;
  /** サイコロを振っている間の連続音。 */
  playRattle(): void;
  /** サイコロが弾んだ瞬間の音。 */
  playThud(): void;
  /** 駒が1マス進むごとの足音。 */
  playStep(): void;
  /** 汎用的な獲得音(ダイス確定・青マス・売却など)。 */
  playCoin(): void;
  /** 損失・不正解・赤マスの音。 */
  playWrong(): void;
  /** クイズ正解の音。 */
  playRight(): void;
  /** 購入・増資・屋台での買い物の音。 */
  playBuy(): void;
  /** ルーレット(青・赤マス)のスピン中のティック音。 */
  playTick(): void;
  /** 季節の変わり目・カードマスでの入手音。 */
  playChime(): void;
  /** 独占達成のファンファーレ。 */
  playFanfare(): void;
  /**
   * 目的地に着いたときの、少し長い到着の音楽。
   * 旅のひと区切りなので、他の効果音より一段華やかにする。
   */
  playArrival(): void;
  /**
   * 何も起きないマスに着いたときの、短い汽笛。
   *
   * **出来事ではなく返事。**無印マスに止まると、駒が動いたあとは無音のまま
   * 次の人の手番に切り替わっていて、操作が受理されたのか分からなかった。
   */
  playWhistle(): void;
  /** 厄災の神の発動音。 */
  playDoom(isKing: boolean): void;
  /** ゲーム終了時の勝利音。 */
  playWin(): void;
  /**
   * BGMを止める(効果音は止めない)。
   * ミュート設定そのものは変えないので、次にBGMを指定すればまた鳴り始める。
   * 旅を終えてセットアップ画面へ戻るときに呼ぶ。
   */
  stopMusic(): void;
  /**
   * BGMを鳴らすかどうかの設定。プレイヤーが画面から切り替える。
   *
   * `setMuted` と違い、**効果音は止めない**。止めたいのは鳴り続けている音楽の方で、
   * サイコロや購入の音は自分の操作への返事なので残す。
   * offのあいだは国やトップ画面が曲を指定しても鳴らず、onに戻すとその曲から鳴り出す。
   */
  setMusicEnabled(enabled: boolean): void;
  setMuted(muted: boolean): void;
}
